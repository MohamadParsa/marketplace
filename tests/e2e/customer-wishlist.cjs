async (cliPage) => {
  const browser = cliPage.context().browser();
  const origin = 'http://localhost:5197';
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await ctx.newPage();
  await page.route('**/storefront/account/recently-viewed/*', route => route.request().method() === 'POST' ? route.fulfill({ json: { recorded: true } }) : route.continue());
  const checks = [], errors = [];
  const check = (id, pass) => { checks.push({ id, pass: !!pass }); if (!pass) throw Error(id); };
  const until = async fn => { for (let i = 0; i < 100; i++) { if (await fn()) return; await page.waitForTimeout(50); } throw Error('condition timed out'); };
  page.on('pageerror', e => errors.push(e.message));
  const listURL = origin + '/storefront/account/wishlist';
  const home = await (await ctx.request.get(origin + '/storefront/home')).json();
  const unique = [...new Map(home.rails.flatMap(r => r.products).map(p => [p.id, p])).values()];
  const [first, second] = unique;
  if (!second) throw Error('two published catalog products required');
  let tokenA = '', tokenB = '';
  const previous = new Map();
  const api = async (token, method, id) => {
    const r = await ctx.request.fetch(listURL + (id ? '/' + encodeURIComponent(id) : ''), { method, headers: { Authorization: 'Bearer ' + token } });
    if (!r.ok()) throw Error('wishlist API status ' + r.status()); return r.json();
  };
  const heart = () => page.locator('.pdp-wishlist button');
  const count = () => page.locator('.header-wishlist .lh-cart-count');
  const openHeaderList = async () => { await page.getByRole('link', { name: 'علاقه‌مندی‌ها', exact: true }).first().click(); await page.waitForURL('**/account/wishlist'); await page.getByRole('heading', { name: 'علاقه‌مندی‌های من', exact: true }).waitFor(); };
  try {
    await page.goto(origin + '/account/wishlist');
    check('guest-list-requires-login', await page.getByRole('link', { name: 'ورود به حساب', exact: true }).isVisible());
    check('guest-header-heart-hidden', await page.locator('.header-wishlist').count() === 0);
    await page.goto(origin + first.url);
    await heart().waitFor();
    await heart().click();
    await page.waitForURL('**/login?**');
    check('guest-heart-returns-to-product', new URL(page.url()).searchParams.get('return') === first.url);
    await page.getByLabel('موبایل یا ایمیل', { exact: true }).fill('09000000001');
    await page.getByRole('button', { name: 'ورود با OTP / ثبت‌نام', exact: true }).click();
    await page.getByRole('button', { name: 'دریافت کد تأیید', exact: true }).click();
    const otp = (await page.locator('.buy-note b').textContent()).trim();
    await page.getByLabel('کد تأیید', { exact: true }).fill(otp);
    await page.getByRole('button', { name: 'تأیید و ورود', exact: true }).click();
    await page.waitForURL('**' + first.url);
    tokenA = await page.evaluate(() => sessionStorage.getItem('cherriva:customer-token'));
    for (const p of [first, second]) previous.set(p.id, (await api(tokenA, 'GET', p.id)).saved);
    const baseline = (await api(tokenA, 'GET')).total;
    // Ensure a stable known initial state for only these two synthetic-user bookmarks.
    for (const p of [first, second]) await api(tokenA, 'DELETE', p.id);
    await page.reload(); await heart().waitFor(); await until(async () => await heart().isEnabled());
    check('initial-pdp-state-not-saved', await heart().getAttribute('aria-pressed') === 'false' && await heart().locator('svg').getAttribute('fill') === 'none');
    await heart().focus(); await heart().press('Space');
    await until(async () => await heart().getAttribute('aria-pressed') === 'true');
    check('keyboard-adds-favorite', (await api(tokenA, 'GET', first.id)).saved);
    check('header-heart-next-to-cart-after-login', await page.locator('.header-wishlist').evaluate(e => e.nextElementSibling.matches('a[href="/cart"]')));
    check('pdp-heart-icon-only-unframed', await heart().evaluate(e => e.textContent.trim() === '' && getComputedStyle(e).borderTopWidth === '0px' && getComputedStyle(e).backgroundColor === 'rgba(0, 0, 0, 0)'));
    check('pdp-heart-filled-when-saved', await heart().locator('svg').getAttribute('fill') === 'currentColor');
    const firstTotal = (await api(tokenA, 'GET')).total;
    await api(tokenA, 'PUT', first.id);
    check('duplicate-put-no-second-row', (await api(tokenA, 'GET')).total === firstTotal);
    await until(async () => await count().isVisible());
    check('header-count-updates', (await count().textContent()).trim() === firstTotal.toLocaleString('fa-IR'));
    await page.screenshot({ path: 'output/playwright/issue-63/pdp-desktop.png', animations: 'disabled' });
    await openHeaderList();
    await page.locator('[data-product-id="' + first.id + '"]').waitFor();
    check('saved-product-in-list', await page.getByRole('link', { name: new RegExp(first.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')) }).count() > 0);
    await page.reload(); await page.locator('[data-product-id="' + first.id + '"]').waitFor();
    check('list-persists-refresh', await page.locator('[data-product-id="' + first.id + '"]').isVisible());
    await page.goto(origin + first.url); await heart().waitFor(); await until(async () => await heart().isEnabled());
    check('pdp-loaded-saved-state-after-refresh', await heart().getAttribute('aria-pressed') === 'true');
    await page.goto(origin + second.url); await heart().waitFor(); await until(async () => await heart().isEnabled());
    const putRoute = '**/storefront/account/wishlist/' + second.id;
    await page.route(putRoute, route => route.request().method() === 'PUT' ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"code":"unavailable"}' }) : route.continue());
    await heart().click(); await page.locator('.pdp-wishlist [role="alert"]').waitFor();
    check('failed-add-preserves-state', await heart().getAttribute('aria-pressed') === 'false' && !(await api(tokenA, 'GET', second.id)).saved);
    await page.unroute(putRoute); await heart().click();
    await until(async () => await heart().getAttribute('aria-pressed') === 'true');
    check('retry-add-succeeds', (await api(tokenA, 'GET', second.id)).saved);
    await openHeaderList(); await page.locator('[data-product-id="' + second.id + '"]').waitFor();
    await page.screenshot({ path: 'output/playwright/issue-63/list-desktop.png', animations: 'disabled' });
    const remove = page.getByRole('button', { name: 'حذف از علاقه‌مندی‌ها: ' + second.name, exact: true });
    await page.route(putRoute, route => route.request().method() === 'DELETE' ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"code":"unavailable"}' }) : route.continue());
    await remove.click(); await page.locator('[role="alert"]').waitFor();
    check('failed-remove-preserves-row', await page.locator('[data-product-id="' + second.id + '"]').isVisible());
    await page.unroute(putRoute); await remove.click();
    await until(async () => await page.locator('[data-product-id="' + second.id + '"]').count() === 0);
    check('remove-keeps-other-bookmark', await page.locator('[data-product-id="' + first.id + '"]').isVisible() && (await api(tokenA, 'GET', first.id)).saved);
    await page.setViewportSize({ width: 390, height: 844 });
    check('mobile-header-heart-visible', await page.locator('.header-wishlist').isVisible());
    check('mobile-no-page-overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: 'output/playwright/issue-63/list-mobile.png', animations: 'disabled' });
    // Visibility/stock/pagination browser edge cases are mocked GETs; real API visibility is covered in Go.
    let fixtureMode = 'hidden', lastRemoved = false;
    await page.route('**/storefront/account/wishlist?*', async route => {
      const u = new URL(route.request().url());
      if (!u.searchParams.has('page')) return route.continue();
      const n = Number(u.searchParams.get('page'));
      const items = fixtureMode === 'hidden' ? [{ product_id: first.id, product: null }] : fixtureMode === 'stock' ? [{ product_id: first.id, product: { ...first, available: false, price: null } }] : n === 2 && !lastRemoved ? [{ product_id: 'browser-page-2', product: null }] : Array.from({ length: 24 }, (_, i) => ({ product_id: 'browser-page-1-' + i, product: null }));
      return route.fulfill({ json: { items, total: fixtureMode === 'pages' ? lastRemoved ? 24 : 25 : 1, page: n, page_size: 24 } });
    });
    await page.reload(); await page.getByRole('heading', { name: 'این کالا دیگر در دسترس نیست', exact: true }).waitFor();
    check('hidden-product-generic-removable-row', await page.getByRole('button', { name: 'حذف از علاقه‌مندی‌ها: کالای غیرقابل‌دسترسی', exact: true }).isVisible() && await page.locator('.wishlist-grid a').count() === 0 && await page.locator('.wishlist-grid img').count() === 0);
    await page.screenshot({ path: 'output/playwright/issue-63/unavailable-mobile.png', animations: 'disabled' });
    fixtureMode = 'stock'; await page.reload(); await page.locator('[data-product-id="' + first.id + '"]').waitFor();
    check('out-of-stock-remains-visible', await page.locator('.wishlist-grid').getByText('ناموجود', { exact: true }).isVisible());
    fixtureMode = 'pages'; await page.reload(); await page.getByRole('navigation', { name: 'صفحه‌بندی علاقه‌مندی‌ها' }).waitFor();
    await page.getByRole('button', { name: 'بعدی', exact: true }).click();
    await until(async () => await page.locator('.wishlist-item').count() === 1);
    check('pagination-second-page', (await page.locator('.wishlist-pagination').textContent()).includes('۲'));
    await page.route('**/storefront/account/wishlist/browser-page-2', async route => { lastRemoved = true; return route.fulfill({ json: { product_id: 'browser-page-2', saved: false, total: 24 } }); });
    await page.getByRole('button', { name: 'حذف از علاقه‌مندی‌ها: کالای غیرقابل‌دسترسی', exact: true }).click();
    await until(async () => await page.locator('.wishlist-item').count() === 24);
    check('delete-last-page-returns-to-valid-page', await page.locator('.wishlist-pagination').count() === 0);
    await page.unroute('**/storefront/account/wishlist?*');
    await page.unroute('**/storefront/account/wishlist/browser-page-2');
    await page.locator('.lh-profile-menu summary').click(); await page.locator('.lh-profile-menu').getByRole('button', { name: 'خروج', exact: true }).click();
    await page.getByRole('link', { name: 'ورود به حساب', exact: true }).waitFor();
    check('logout-clears-private-list-and-badge', await page.locator('.wishlist-grid').count() === 0 && await count().count() === 0);
    const challenge = await (await ctx.request.post(origin + '/storefront/auth/request-otp', { data: { phone: '09000000002' } })).json();
    if (!challenge.test_code) throw Error('local OTP unavailable');
    const login = await (await ctx.request.post(origin + '/storefront/auth/verify-otp', { data: { request_id: challenge.request_id, code: challenge.test_code } })).json(); tokenB = login.token;
    if (!tokenB) throw Error('second synthetic login failed');
    await page.evaluate(token => sessionStorage.setItem('cherriva:customer-token', token), tokenB);
    await page.reload(); await page.getByRole('heading', { name: 'هنوز کالایی ذخیره نکرده‌اید', exact: true }).waitFor();
    check('second-user-does-not-see-first-user-list', await page.locator('.wishlist-grid').count() === 0);
    await api(tokenB, 'DELETE', first.id);
    check('second-user-cannot-delete-first-user-bookmark', (await api(tokenA, 'GET', first.id)).saved);
    await page.evaluate(token => sessionStorage.setItem('cherriva:customer-token', token), tokenA);
    await page.goto(origin + first.url); await heart().waitFor(); await until(async () => await heart().isEnabled());
    check('returning-account-restores-own-heart', await heart().getAttribute('aria-pressed') === 'true');
    await page.setViewportSize({ width: 320, height: 740 });
    check('narrow-mobile-no-page-overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    check('no-runtime-page-errors', errors.length === 0);
    return { checks, errors, sample_product_url: first.url, actual_catalog: true, mock_edges: ['hidden', 'out-of-stock', 'pagination', '503', 'history-recording-out-of-scope'], only_own_synthetic_wishlist_mutated: true, restored_previous_bookmarks: true };
  } finally {
    if (tokenA) for (const [id, saved] of previous) await api(tokenA, saved ? 'PUT' : 'DELETE', id);
    await ctx.close();
  }
}
