"""بررسی رابط نمونه سایت مشتری؛ اجرا با Chrome نصب‌شده و URL اختیاری."""
import sys
from playwright.sync_api import sync_playwright, expect

base_url = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:5174'
with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True, channel='chrome')
    page = browser.new_page(viewport={'width': 1440, 'height': 1000})
    page.set_default_timeout(8000)
    page.set_extra_http_headers({'Cache-Control': 'no-cache'})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    print('Loading catalog', flush=True)
    page.goto(base_url, wait_until='networkidle', timeout=20000)
    page.evaluate('document.fonts.ready')
    expect(page.locator('.product-card')).to_have_count(8)
    assert page.locator('img').evaluate_all('(images) => images.every(image => image.complete && image.naturalWidth > 0)')
    assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
    expect(page.locator('.product-card').last).to_contain_text('ناموجود')
    expect(page.get_by_role('button', name='افزودن هدفون بی‌سیم استودیو به سبد', exact=True)).to_be_disabled()
    print('Checking cart', flush=True)
    page.get_by_label('رنگ یا نوع هدفون بی‌سیم استودیو', exact=True).select_option('مشکی')
    page.get_by_role('button', name='افزودن هدفون بی‌سیم استودیو به سبد', exact=True).click()
    expect(page.get_by_role('status')).to_contain_text('اضافه شد')
    page.get_by_role('button', name='سبد خرید، 1 کالا').click()
    expect(page.locator('.cart-total')).to_contain_text('۲٬۴۵۰٬۰۰۰')
    page.get_by_label('فروشگاه هدفون بی‌سیم استودیو در سبد').select_option('pearl')
    expect(page.locator('.cart-store h3')).to_have_text('فروشگاه مروارید')
    expect(page.locator('.cart-total')).to_contain_text('۲٬۴۹۵٬۰۰۰')
    page.get_by_label('افزایش تعداد هدفون بی‌سیم استودیو', exact=True).click()
    expect(page.locator('.cart-total')).to_contain_text('۴٬۹۹۰٬۰۰۰')
    page.get_by_label('نوع هدفون بی‌سیم استودیو در سبد').select_option('نقره‌ای')
    page.get_by_role('button', name='بستن', exact=True).click()
    print('Checking cart', flush=True)
    page.get_by_label('رنگ یا نوع هدفون بی‌سیم استودیو', exact=True).select_option('نقره‌ای')
    page.get_by_role('button', name='افزودن هدفون بی‌سیم استودیو به سبد', exact=True).click()
    page.get_by_role('button', name='سبد خرید، 3 کالا').click()
    expect(page.locator('.cart-line')).to_have_count(2)
    page.get_by_label('فروشگاه هدفون بی‌سیم استودیو در سبد').last.select_option('cherry')
    expect(page.locator('.cart-line')).to_have_count(1)
    expect(page.locator('.cart-total')).to_contain_text('۷٬۳۵۰٬۰۰۰')
    for _ in range(5):
        page.get_by_label('افزایش تعداد هدفون بی‌سیم استودیو', exact=True).click()
    expect(page.get_by_label('افزایش تعداد هدفون بی‌سیم استودیو', exact=True)).to_be_disabled()
    page.get_by_role('button', name='حذف', exact=True).click()
    expect(page.locator('dialog')).to_contain_text('سبدت منتظر انتخاب توست')
    page.keyboard.press('Escape')
    expect(page.locator('dialog')).to_have_count(0)
    print('Checking filters', flush=True)
    page.get_by_role('searchbox').fill('چیزی که وجود ندارد')
    expect(page.locator('.product-card')).to_have_count(0)
    expect(page.locator('.empty')).to_contain_text('هنوز چیزی پیدا نکردیم')
    page.get_by_role('button', name='نمایش همه کالاها', exact=True).click()
    page.get_by_label('فروشگاه', exact=True).select_option('pearl')
    expect(page.locator('.product-card').first).to_contain_text('۲٬۴۹۵٬۰۰۰')
    page.get_by_role('button', name='حذف فیلترها', exact=True).click()
    page.get_by_label('مرتب‌سازی', exact=True).select_option('cheap')
    expect(page.locator('.product-card').first).to_contain_text('چای دست‌چین')
    expect(page.locator('.product-card').last).to_contain_text('ناموجود')
    page.get_by_label('حداکثر قیمت').focus()
    page.keyboard.press('Home')
    for _ in range(10):
        page.keyboard.press('ArrowRight')
    expect(page.locator('.product-card')).to_have_count(3)
    page.get_by_role('button', name='حذف فیلترها', exact=True).click()
    page.get_by_role('button', name='مشاهده هدفون بی‌سیم استودیو', exact=True).click()
    expect(page.locator('dialog')).to_be_visible()
    page.locator('dialog').get_by_label('رنگ / نوع', exact=True).select_option('مشکی')
    page.locator('.store-choice').last.click()
    page.get_by_role('spinbutton').fill('1.5')
    expect(page.get_by_role('spinbutton')).to_have_value('1')
    page.get_by_role('spinbutton').fill('2')
    expect(page.locator('.detail-price')).to_contain_text('۴٬۹۹۰٬۰۰۰')
    page.get_by_role('button', name='افزودن به سبد خرید', exact=True).click()
    expect(page.locator('dialog')).to_have_count(0)
    expect(page.get_by_role('status')).to_contain_text('اضافه شد')
    page.goto(base_url + '/?product=watch', wait_until='networkidle')
    expect(page.get_by_role('dialog')).to_contain_text('ساعت مچی کلاسیک')
    page.keyboard.press('Escape')
    print('Loading catalog', flush=True)
    page.goto(base_url, wait_until='networkidle', timeout=20000)
    page.evaluate('document.fonts.ready')
    page.screenshot(path='/tmp/cherriva-desktop.png', full_page=True)
    for width in (390, 320, 768):
        page.set_viewport_size({'width': width, 'height': 844})
        assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), f'overflow at {width}px'
    page.set_viewport_size({'width': 390, 'height': 844})
    page.get_by_role('button', name='مشاهده ماگ سرامیکی مینیمال', exact=True).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.keyboard.press('Escape')
    page.screenshot(path='/tmp/cherriva-mobile.png', full_page=True)
    assert not errors, errors
    browser.close()
print('PASS: catalog, filters, stock, variants, vendors, cart merging/totals, modal, direct link, responsive layout, assets, and console')
