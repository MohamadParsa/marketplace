"""بررسی جریان سایت نمونه تا صفحه پرداخت؛ بدون تماس با درگاه یا ثبت سفارش."""
import sys
from datetime import datetime, timedelta, timezone
from playwright.sync_api import sync_playwright, expect

base_url = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:5174'
with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True, channel='chrome')
    page = browser.new_page(viewport={'width': 1440, 'height': 1000})
    page.set_default_timeout(10000)
    page.set_extra_http_headers({'Cache-Control': 'no-cache'})
    page.clock.install()
    errors, writes = [], []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.on('request', lambda request: writes.append(request.url) if request.method != 'GET' else None)
    page.goto(base_url, wait_until='networkidle')
    expect(page.locator('.header .brand-letter')).to_have_attribute('src', '/brand/open-c-main-symbol.svg')
    expect(page.locator('.header .brand-tail img')).to_have_attribute('src', '/brand/open-c-main.svg')
    assert page.locator('.header .brand-logo img').evaluate_all('(images) => images.every(image => image.complete && image.naturalWidth > 0)')
    expect(page.locator('link[rel=icon]')).to_have_attribute('href', '/brand/open-c-main-symbol.svg')
    page.get_by_role('button', name='افزودن چای دست‌چین بهاره به سبد', exact=True).click()
    expect(page.locator('[data-product=cup]').get_by_role('button', name='سفید', exact=True)).to_have_attribute('aria-pressed', 'true')
    page.get_by_label('فروشگاه', exact=True).select_option('pearl')
    page.get_by_role('button', name='افزودن ماگ سرامیکی مینیمال به سبد', exact=True).click()
    page.get_by_role('button', name='سبد خرید، 2 کالا').click()
    expect(page.locator('.cart-total')).to_contain_text('۷۲۵٬۰۰۰')
    page.get_by_role('button', name='ادامه خرید و انتخاب آدرس').click()
    expect(page.locator('nav[aria-label="مراحل خرید"]')).to_be_visible()
    expect(page.locator('.summary-products>div')).to_have_count(2)
    print('Testing sample OTP and account', flush=True)
    page.get_by_label('شماره همراه حساب').fill('09123456789')
    page.get_by_role('button', name='دریافت کد آزمایشی').click()
    expect(page.get_by_role('alert')).to_contain_text('فقط شماره حساب نمونه')
    page.get_by_label('شماره همراه حساب').fill('۰۹۰۰۰۰۰۰۰۰۳')
    page.get_by_role('button', name='دریافت کد آزمایشی').click()
    expect(page.get_by_label('شماره همراه حساب')).to_be_disabled()
    expect(page.get_by_role('button', name='ارسال مجدد پس از ۶۰ ثانیه')).to_be_disabled()
    page.get_by_label('کد یک‌بارمصرف').fill('000000')
    page.get_by_role('button', name='تأیید و ادامه').click()
    expect(page.get_by_role('alert')).to_contain_text('صحیح نیست')
    page.get_by_label('کد یک‌بارمصرف').fill('۱۲۳۴۵۶')
    page.get_by_role('button', name='تأیید و ادامه').click()
    expect(page.locator('.checkout-section-title')).to_contain_text('اطلاعات و مقصد')
    expect(page.locator('.summary-products>div')).to_have_count(2)
    page.get_by_role('button', name='تأیید اطلاعات و انتخاب ارسال').click()
    expect(page.get_by_role('alert')).to_contain_text('نام و نام خانوادگی')
    page.get_by_label('نام صاحب حساب', exact=True).fill('مریم')
    page.get_by_label('نام خانوادگی صاحب حساب', exact=True).fill('آزمایشی')
    print('Testing address validation, recipient and coverage', flush=True)
    page.get_by_role('button', name='افزودن آدرس').click()
    editor = page.get_by_role('region', name='فرم آدرس')
    editor.get_by_label('عنوان آدرس', exact=True).fill('مقصد جدید نمونه')
    editor.get_by_label('نام کامل گیرنده', exact=True).fill('رضا نمونه')
    editor.get_by_label('شماره تماس گیرنده', exact=True).fill('۰۹۰۰۰۰۰۰۰۰۴')
    editor.get_by_label('کدپستی', exact=True).fill('123')
    editor.get_by_label('نشانی کامل', exact=True).fill('خیابان تست، ساختمان نمونه، پلاک ۳')
    editor.get_by_role('button', name='ذخیره آدرس در این مرور').click()
    expect(editor.get_by_role('alert')).to_contain_text('۱۰ رقم')
    editor.get_by_label('کدپستی', exact=True).fill('۳۳۳۳۳۳۳۳۳۳')
    editor.get_by_label('استان آدرس', exact=True).select_option('فارس')
    editor.get_by_role('button', name='ذخیره آدرس در این مرور').click()
    expect(page.locator('.address-card')).to_have_count(3)
    page.get_by_role('button', name='تأیید اطلاعات و انتخاب ارسال').click()
    expect(page.locator('.shipping-group')).to_have_count(2)
    expect(page.get_by_role('button', name='ادامه پرداخت', exact=True)).to_be_disabled()
    expect(page.get_by_role('alert')).to_have_count(2)
    page.get_by_role('button', name='تغییر آدرس').click()
    page.get_by_role('button', name='ویرایش مقصد جدید نمونه').click()
    editor.get_by_label('استان آدرس', exact=True).select_option('تهران')
    editor.get_by_role('button', name='ذخیره آدرس در این مرور').click()
    page.get_by_role('button', name='تأیید اطلاعات و انتخاب ارسال').click()
    print('Testing per-store shipping and confirmation', flush=True)
    for group in page.locator('.shipping-group').all():
        group.get_by_role('radio').first.check()
    expect(page.locator('.checkout-totals .summary-total')).to_contain_text('۸۶۵٬۰۰۰')
    expect(page.get_by_role('button', name='ادامه پرداخت', exact=True)).to_be_disabled()
    page.get_by_role('checkbox').check()
    page.get_by_role('button', name='ادامه پرداخت', exact=True).click()
    expect(page.get_by_label('زمان باقی‌مانده پرداخت')).to_have_text('10:00')
    expect(page.locator('.wallet-deficit')).to_contain_text('۶۶۵٬۰۰۰')
    expect(page.get_by_label('مبلغ شارژ کیف پول (تومان)')).to_have_value('665000')
    page.get_by_label('مبلغ شارژ کیف پول (تومان)').fill('1')
    expect(page.get_by_role('alert')).to_contain_text('حداقل برابر کسری')
    page.get_by_label('مبلغ شارژ کیف پول (تومان)').fill('۷۰۰۰۰۰')
    expect(page.locator('.wallet-panel')).to_contain_text('۳۵٬۰۰۰ تومان')
    expect(page.get_by_role('button', name='شارژ کیف پول و ادامه')).to_be_disabled()
    assert page.locator('.checkout-summary').inner_text().count('فروشگاه') >= 2
    page.evaluate('document.fonts.ready')
    page.screenshot(path='/tmp/cherriva-payment-desktop.png', full_page=True)
    for width in (320, 390, 768):
        page.set_viewport_size({'width':width,'height':844})
        assert not page.evaluate('document.documentElement.scrollWidth>innerWidth'), f'overflow at {width}'
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path='/tmp/cherriva-payment-mobile.png', full_page=True)
    page.locator('.payment-method').last.get_by_role('radio').check()
    expect(page.locator('.bnpl-panel')).to_contain_text('هنوز انتخاب نشده')
    expect(page.locator('.bnpl-panel button')).to_be_disabled()
    page.locator('.payment-method').first.get_by_role('radio').check()
    print('Testing session expiry and return to cart', flush=True)
    page.clock.set_system_time(datetime.now(timezone.utc) + timedelta(minutes=11))
    page.clock.run_for(1000)
    expect(page.get_by_label('زمان باقی‌مانده پرداخت')).to_have_text('00:00')
    expect(page.locator('.expiry-panel')).to_be_visible()
    expect(page.locator('.payment-method')).to_have_count(0)
    expect(page.locator('.checkout-stepper button').nth(1)).to_be_disabled()
    page.get_by_role('button', name='بازگشت به سبد و بررسی دوباره').click()
    expect(page.locator('.cart-line')).to_have_count(2)
    expect(page.locator('.cart-total')).to_contain_text('۷۲۵٬۰۰۰')
    page.get_by_role('button', name='ادامه خرید و انتخاب آدرس').click()
    expect(page.get_by_label('نام صاحب حساب', exact=True)).to_have_value('مریم')
    expect(page.locator('.address-card.selected')).to_contain_text('رضا نمونه')
    expect(page.locator('.address-card')).to_have_count(3)
    page.get_by_role('button', name='تأیید اطلاعات و انتخاب ارسال').click()
    page.get_by_role('checkbox').check()
    page.get_by_role('button', name='ادامه پرداخت', exact=True).click()
    expect(page.get_by_label('زمان باقی‌مانده پرداخت')).to_have_text('10:00')
    assert page.evaluate('localStorage.length===0 && sessionStorage.length===0')
    assert not errors, errors
    assert not writes, writes
    page.reload(wait_until='networkidle')
    expect(page.locator('.checkout-main')).to_contain_text('سبد قابل ادامه نیست')
    print('Testing OTP expiry, resend and attempt limit', flush=True)
    otp_page = browser.new_page()
    otp_page.set_default_timeout(10000)
    otp_page.clock.install()
    otp_page.goto(base_url, wait_until='networkidle')
    otp_page.get_by_role('button', name='ورود / ثبت‌نام').click()
    otp_page.get_by_role('button', name='دریافت کد آزمایشی').click()
    otp_page.clock.run_for(91000)
    expect(otp_page.get_by_role('button', name='تأیید و ادامه')).to_be_disabled()
    otp_page.get_by_role('button', name='دریافت دوباره کد').click()
    expect(otp_page.get_by_role('button', name='ارسال مجدد پس از ۶۰ ثانیه')).to_be_disabled()
    otp_page.get_by_label('کد یک‌بارمصرف').fill('000000')
    for _ in range(5):
        otp_page.get_by_role('button', name='تأیید و ادامه').click()
    otp_page.get_by_label('کد یک‌بارمصرف').fill('123456')
    otp_page.get_by_role('button', name='تأیید و ادامه').click()
    expect(otp_page.get_by_role('alert')).to_contain_text('سقف ۵ تلاش')
    browser.close()
print('PASS: logo, OTP, profile, address validation/selection, recipient, shipping, totals, payment methods, expiry, retained cart, responsive layout, no writes/storage')
